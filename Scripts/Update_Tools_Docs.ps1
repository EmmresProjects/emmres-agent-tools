[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$ToolsRoot = Join-Path $RepoRoot 'Tools'
$DocsRoot = Join-Path $RepoRoot 'docs'
$DocsToolsRoot = Join-Path $DocsRoot 'tools'

if (-not (Test-Path -LiteralPath $ToolsRoot -PathType Container)) { throw "Missing Tools folder: $ToolsRoot" }
if (-not (Test-Path -LiteralPath $DocsRoot -PathType Container)) { New-Item -ItemType Directory -Path $DocsRoot | Out-Null }
if (-not (Test-Path -LiteralPath $DocsToolsRoot -PathType Container)) { New-Item -ItemType Directory -Path $DocsToolsRoot | Out-Null }

function Write-Utf8NoBom([string]$Path, [string[]]$Lines) {
    $Text = ($Lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText($Path, $Text, [System.Text.UTF8Encoding]::new($false))
}

function Get-FirstDescription([string]$ReadmePath) {
    if (-not (Test-Path -LiteralPath $ReadmePath -PathType Leaf)) { return 'No description supplied.' }
    $lines = Get-Content -LiteralPath $ReadmePath -Encoding UTF8
    $parts = New-Object System.Collections.Generic.List[string]
    $inFence = $false
    foreach ($raw in $lines) {
        $line = $raw.Trim()
        if ($line -match '^```') { $inFence = -not $inFence; continue }
        if ($inFence -or [string]::IsNullOrWhiteSpace($line)) {
            if ($parts.Count -gt 0) { break }
            continue
        }
        if ($line -match '^(#|---|\|)' -or $line -match '^[-*+]\s' -or $line -match '^\d+\.\s') { continue }
        $parts.Add($line)
        if (($parts -join ' ').Length -ge 220) { break }
    }
    if ($parts.Count -eq 0) { return 'See the package README for details.' }
    $text = ($parts -join ' ') -replace '\[([^\]]+)\]\([^\)]+\)', '$1'
    $text = $text -replace '[|\r\n]+',' ' -replace '\s+',' '
    if ($text.Length -gt 280) { $text = $text.Substring(0,277).TrimEnd() + '...' }
    return $text.Trim()
}

function Get-YamlValue([string]$YamlPath, [string]$Key, [string]$Fallback) {
    if (Test-Path -LiteralPath $YamlPath -PathType Leaf) {
        $match = Get-Content -LiteralPath $YamlPath -Encoding UTF8 | Where-Object { $_ -match "^\s*$([Regex]::Escape($Key))\s*:\s*(.+?)\s*$" } | Select-Object -First 1
        if ($match -and $match -match "^\s*$([Regex]::Escape($Key))\s*:\s*(.+?)\s*$") {
            $value = $Matches[1].Trim().Trim('"').Trim("'")
            if ($value) { return $value }
        }
    }
    return $Fallback
}

$categories = Get-ChildItem -LiteralPath $ToolsRoot -Directory | Sort-Object Name
$allTools = New-Object System.Collections.Generic.List[object]

foreach ($category in $categories) {
    $items = Get-ChildItem -LiteralPath $category.FullName -Directory | Where-Object { $_.Name -notin @('.git','__pycache__') } | Sort-Object Name
    $categorySlug = $category.Name.ToLowerInvariant() -replace '[^a-z0-9]+','-'
    $categoryLines = @("# $($category.Name) Tools", '', "Generated from ``Tools/$($category.Name)/``. Do not edit this page by hand; edit each package README or tool.yaml, then run ``Update_Tools_Docs.bat``.", '')

    if ($items.Count -eq 0) {
        $categoryLines += '_No tool packages found in this category._'
    } else {
        foreach ($item in $items) {
            $yaml = Join-Path $item.FullName 'tool.yaml'
            $readme = Join-Path $item.FullName 'README.md'
            if (-not (Test-Path -LiteralPath $readme)) {
                $fallbackReadme = Get-ChildItem -LiteralPath $item.FullName -File -Filter '*.md' | Where-Object Name -Match 'readme' | Select-Object -First 1
                if ($fallbackReadme) { $readme = $fallbackReadme.FullName }
            }
            $name = Get-YamlValue $yaml 'name' ($item.Name -replace '[-_]',' ')
            $status = Get-YamlValue $yaml 'status' 'Unspecified'
            $version = Get-YamlValue $yaml 'version' 'Unspecified'
            $description = Get-FirstDescription $readme
            $repoPath = "Tools/$($category.Name)/$($item.Name)/"
            $categoryLines += @("## $name", '', $description, '', "- **Status:** $status", "- **Version:** $version", "- **Repository path:** ``$repoPath``", '')
            $allTools.Add([pscustomobject]@{ Name=$name; Category=$category.Name; Purpose=$description; Status=$status; Version=$version; Path=$repoPath })
        }
    }
    Write-Utf8NoBom (Join-Path $DocsToolsRoot "$categorySlug.md") $categoryLines
}

$catalog = @('# Tool Catalog', '', 'Generated from the immediate package folders under `Tools/<Category>/`. Do not edit this file by hand.', '', '| Tool | Category | Purpose | Status | Version |', '|---|---|---|---|---|')
if ($allTools.Count -eq 0) { $catalog += '| No tools found | | Add package folders under `Tools/<Category>/` | | |' }
else {
    foreach ($tool in $allTools | Sort-Object Category,Name) {
        $purpose = $tool.Purpose -replace '\|','\|'
        $catalog += "| $($tool.Name) | $($tool.Category) | $purpose | $($tool.Status) | $($tool.Version) |"
    }
}
Write-Utf8NoBom (Join-Path $DocsRoot 'catalog.md') $catalog

$index = @("# Emmre's Agent Tools", '', 'A documented collection of reusable tools and capability packages.', '', '## Start here', '- [Tool catalog](catalog.md)', '- [Getting started](getting-started.md)', '- [Adding a tool](adding-a-tool.md)', '- [Requirements](requirements.md)', '- [Safety](safety.md)', '', '## Browse by category')
foreach ($category in $categories) {
    $slug = $category.Name.ToLowerInvariant() -replace '[^a-z0-9]+','-'
    $index += "- [$($category.Name)](tools/$slug.md)"
}
$index += @('', '## Inventory', "- **Categories:** $($categories.Count)", "- **Tool packages:** $($allTools.Count)", '', '## Important', 'These pages describe tools. Documentation does not itself give an Agent Builder agent permission or a runtime to execute them.')
Write-Utf8NoBom (Join-Path $DocsRoot 'index.md') $index

Write-Host "Updated index.md, catalog.md, and $($categories.Count) category pages."
Write-Host "Found $($allTools.Count) tool package(s)."
