#!/usr/bin/env node
/**
 * Cordova after_prepare hook
 * ------------------------------------------------------------------
 * 1. Tells the Android manifest to allow background sync.
 * 2. Copies APP_VERSION into the built www so the Settings screen
 *    always shows the version that was actually packaged.
 * 3. Fails fast if a required app file is missing, so a broken APK is
 *    never produced.
 */
'use strict';

const fs = require('fs');
const path = require('path');

module.exports = function (context) {
  const root = context.opts.projectRoot;
  const platform = (context.opts.platforms || [])[0] || '';
  const www = path.join(root, 'www');

  console.log('[{{BRAND_SLUG}}-hook] preparing ' + (platform || 'project'));

  const required = [
    'index.html',
    'css/app.css',
    'js/app.js', 'js/pos.js', 'js/kitchen.js', 'js/db.js',
    'js/api.js', 'js/util.js', 'js/seed.js'
  ];
  const missing = required.filter((f) => !fs.existsSync(path.join(www, f)));
  if (missing.length) {
    throw new Error('[{{BRAND_SLUG}}-hook] Missing app files in www: ' + missing.join(', ') +
      '\nRun "node scripts/sync-www.js" (or npm run sync) before building.');
  }

  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const versionFile = path.join(www, 'js', 'version.js');
  fs.writeFileSync(versionFile,
    '/* generated by cordova/scripts/after-prepare.js */\n' +
    'window.APP_VERSION = ' + JSON.stringify(pkg.version || '{{APP_VERSION}}') + ';\n' +
    'window.APP_BUILD = ' + JSON.stringify(platform) + ';\n' +
    'window.APP_BUILT_AT = ' + JSON.stringify(new Date().toISOString()) + ';\n');
  console.log('[{{BRAND_SLUG}}-hook] version.js written (' + (pkg.version || '{{APP_VERSION}}') + ')');

  // Make sure index.html loads version.js before app.js
  const indexPath = path.join(www, 'index.html');
  let html = fs.readFileSync(indexPath, 'utf8');
  if (html.indexOf('js/version.js') === -1) {
    html = html.replace('<script src="js/util.js"></script>',
      '<script src="js/version.js"></script>\n<script src="js/util.js"></script>');
    fs.writeFileSync(indexPath, html);
    console.log('[{{BRAND_SLUG}}-hook] index.html patched to load version.js');
  }
};
