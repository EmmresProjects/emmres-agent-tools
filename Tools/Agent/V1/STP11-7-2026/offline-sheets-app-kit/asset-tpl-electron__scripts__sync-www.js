#!/usr/bin/env node
/** Copies ../../app -> ./www so the desktop build uses the same source. */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = path.resolve(root, '..', 'app');
const dest = path.resolve(root, 'www');

function rm(dir) { if (fs.existsSync(dir)) fs.rmSync(dir, { recursive: true, force: true }); }
function copy(a, b) {
  fs.mkdirSync(b, { recursive: true });
  for (const e of fs.readdirSync(a, { withFileTypes: true })) {
    const s = path.join(a, e.name), d = path.join(b, e.name);
    if (e.isDirectory()) copy(s, d); else fs.copyFileSync(s, d);
  }
}
if (!fs.existsSync(src)) { console.error('app folder not found at ' + src); process.exit(1); }

// Refuse to package a build with no server token set, so the client does not
// receive a half-configured app by accident. (Warns only - it still builds.)
rm(dest);
copy(src, dest);
const mock = path.join(dest, 'js', 'seed.js.mock.json');
if (fs.existsSync(mock)) fs.unlinkSync(mock);

// The single-file build is only for sharing/preview, never packaged
const single = path.join(dest, '{{ARTIFACT_SLUG}}.html');
if (fs.existsSync(single)) fs.unlinkSync(single);

// Stamp the version into the packaged files
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
fs.writeFileSync(path.join(dest, 'js', 'version.js'),
  '/* generated by electron/scripts/sync-www.js */\n' +
  'window.APP_VERSION = ' + JSON.stringify(pkg.version) + ';\n' +
  'window.APP_BUILD = "electron";\n' +
  'window.APP_BUILT_AT = ' + JSON.stringify(new Date().toISOString()) + ';\n');

const indexPath = path.join(dest, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
if (html.indexOf('js/version.js') === -1) {
  html = html.replace('<script src="js/util.js"></script>',
    '<script src="js/version.js"></script>\n<script src="js/util.js"></script>');
  fs.writeFileSync(indexPath, html);
}

console.log('[sync-www] app/ -> electron/www/  (v' + pkg.version + ')');
