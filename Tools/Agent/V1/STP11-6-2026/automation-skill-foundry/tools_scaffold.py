#!/usr/bin/env python3
"""tools_scaffold.py - build a runnable automation project from a bundle.

Produces a small, real project on disk (dry-run by default):

  <out-dir>/automation_entry.py     runnable entry point from asset-runner-skeleton.py
  <out-dir>/config.json             externalised configuration with paths + limits
  <out-dir>/README.md               install / run / dry-run / recover notes
  <out-dir>/requirements.txt        runtime dependencies (empty by design)
  <out-dir>/fixtures/sample.csv     tiny fixture the normal path can run on
  <out-dir>/run_history.json        idempotent build record
  <out-dir>/automation_entry.py.sha256

Guards: refuses to overwrite an existing project without --force (which archives
the previous version to <out-dir>.bak-<n>), never writes outside --out-dir, and
refuses to write secrets detected in generated text.

Commands
  build    generate the project (dry-run unless --apply is given)
  verify   run a generated project in dry-run mode and report results
  export   emit a scheduler / service launcher bundle for the generated project
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import tools_common as C

PROG = "tools_scaffold.py"
MAX_BACKUPS = 5


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------

def _safe_name(text):
    name = C._slug(text or "automation")
    return name[:60] or "automation"


def _target_dir(args, cfg):
    base = args.out_dir or cfg.get("workspace_dir") or "automation-workspace"
    root = os.path.abspath(base)
    if args.out_dir and not os.path.isabs(args.out_dir):
        root = os.path.abspath(args.out_dir)
    return root


def _render_skeleton(bundle, cfg, extras):
    template = open(C.asset(C.SKELETON_FILE), "r", encoding="utf-8").read()
    tool_name = extras.get("tool_name") or _safe_name(bundle["goal"])
    stages = [s.get("stage", "build") for s in bundle["skills"]]
    seen = []
    for stage in stages:
        if stage not in seen:
            seen.append(stage)
    limits = C.load_rules(root=C.tool_root()).get("limits") or {}
    values = {
        "TOOL_NAME": tool_name,
        "GOAL": (bundle["goal"] or "automation").replace('"', "'"),
        "RETRIES": int(extras.get("retries") or limits.get("max_retries", 3)),
        "TIMEOUT_SECONDS": int(extras.get("timeout")
                               or limits.get("default_job_timeout_seconds", 900)),
        "STAGES": json.dumps(seen),
        "AUDIT_LOG": extras.get("audit_log") or "logs/audit.jsonl",
    }
    for key, value in values.items():
        template = template.replace("{{%s}}" % key, str(value))
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", template)
    if leftover:
        raise C.FoundryError("unreplaced placeholders in skeleton: %s"
                             % ", ".join(sorted(set(leftover))), code="bad_template")
    compile(template, "<skeleton>", "exec")  # syntax check before writing
    return template


def _config_doc(bundle, extras, limits):
    return {
        "goal": bundle["goal"],
        "dry_run_default": True,
        "input_dir": extras.get("input_dir") or "inbox",
        "output_dir": extras.get("output_dir") or "outbox",
        "quarantine_dir": extras.get("quarantine_dir") or "quarantine",
        "audit_log": extras.get("audit_log") or "logs/audit.jsonl",
        "limits": {
            "max_retries": int(extras.get("retries") or limits.get("max_retries", 3)),
            "timeout_seconds": int(extras.get("timeout")
                                   or limits.get("default_job_timeout_seconds", 900)),
            "max_concurrency": int(extras.get("concurrency")
                                   or limits.get("max_concurrency", 1)),
            "max_queue_depth": int(limits.get("max_queue_depth", 10000)),
        },
        "risk": bundle.get("risk") or {},
        "approval_required": bool(bundle.get("approval_required")),
        "approved_by": bundle.get("approved_by"),
        "skills": [{"number": s.get("number"), "name": s["name"], "stage": s.get("stage")}
                   for s in bundle["skills"]],
        "secrets": {"policy": "reference-only",
                    "note": "Never paste credentials here. Read them from the "
                            "environment or a vault reference at runtime."},
    }


def _readme_doc(bundle, cfg, extras, target):
    skills = "\n".join("- %s%s" % (s["name"],
                                   " (skill #%s)" % s["number"] if s.get("number") else "")
                       for s in bundle["skills"])
    return """# %s

Generated by the Automation Skill Foundry from the AutoForge catalog.

## Goal
%s

## Skills this project implements
%s

## Install
```sh
python3 -m pip install -r requirements.txt   # no third-party packages required
```

## Configure
Edit `config.json`: `input_dir`, `output_dir`, `quarantine_dir`, `audit_log`, and
the `limits` block. Secrets are env/vault references only — never inline values.

## Run
```sh
python3 automation_entry.py --dry-run        # preview only, changes nothing
python3 automation_entry.py                  # apply
python3 automation_entry.py --stages         # print the lifecycle stages
```

## Exit codes
0 success · 1 runtime failure · 2 invalid input · 130 cancelled

## Safety
- `--dry-run` is the default posture in `config.json`.
- Audit records land in `%s` (actor, action, result, no raw secrets).
- Retries are bounded to %s attempts; the job aborts after %s seconds.
- Approval is %s for this project.%s

## Recover
1. Read the failing audit line in the audit log.
2. Re-run with `--dry-run` to inspect the intended change set.
3. Restore from the backup/checkpoint noted in the audit entry, then retry once.

## Ownership
Owner: %s · Review: quarterly · Regenerate with `python3 tools_scaffold.py build`.
""" % (
        extras.get("tool_name") or _safe_name(bundle["goal"]),
        bundle["goal"],
        skills,
        extras.get("audit_log") or "logs/audit.jsonl",
        extras.get("retries") or 3,
        extras.get("timeout") or 900,
        "required before apply" if bundle.get("approval_required") else "not required",
        (" Approver on record: %s." % bundle["approved_by"]
         if bundle.get("approved_by") else ""),
        cfg.get("scheduler_owner") or "automation-owner",
    )


def _fixture_csv(bundle):
    header = "record_id,source,received_at,status,notes\n"
    rows = [
        '1,sample,intake,new,"fixture row - safe to delete"',
        '2,sample,intake,new,"second fixture row"',
    ]
    return header + "\n".join(rows) + "\n"


def _fingerprint(text):
    return C.sha256_of(text)


# --------------------------------------------------------------------------
# commands
# --------------------------------------------------------------------------

def cmd_build(args, cfg):
    bundle = C.load_bundle(args.input)
    rules = C.load_rules(root=C.tool_root())
    limits = rules.get("limits") or {}
    target = _target_dir(args, cfg)
    extras = {
        "tool_name": args.tool_name or _safe_name(bundle["goal"]),
        "retries": args.retries,
        "timeout": args.timeout,
        "audit_log": args.audit_log,
        "input_dir": args.input_dir,
        "output_dir": args.output_dir,
    }
    entry_source = _render_skeleton(bundle, cfg, extras)
    config_doc = _config_doc(bundle, extras, limits)
    readme = _readme_doc(bundle, cfg, extras, target)
    fixture = _fixture_csv(bundle)

    files = {
        "automation_entry.py": entry_source,
        "config.json": C.stable_json(config_doc),
        "README.md": readme,
        "requirements.txt": "# no third-party dependencies required\n",
        "fixtures/sample.csv": fixture,
    }
    findings = []
    if cfg.get("secret_scan", True):
        for name, text in files.items():
            for hit in C.scan_for_secrets(text):
                findings.append({"file": name, **hit})
    if findings:
        raise C.FoundryError(
            "refusing to write files that look like they embed credentials",
            code="secret_detected", detail={"findings": findings[:10]})

    if os.path.exists(target) and os.listdir(target):
        if not args.force:
            raise C.FoundryError(
                "target directory already exists and is not empty: %s "
                "(re-run with --force to archive and replace)" % target,
                code="target_exists")
        archive = _archive_existing(target)
    else:
        archive = None

    plan = {
        "target": target,
        "files": sorted(files),
        "bytes": sum(len(t.encode("utf-8")) for t in files.values()),
        "apply": bool(args.apply),
        "archive": archive,
    }
    if not args.apply:
        plan["ok"] = True
        plan["tool"] = PROG
        plan["mode"] = "dry-run"
        plan["note"] = "Nothing was written. Re-run with --apply to create the project."
        plan["previews"] = {name: text[:400] for name, text in files.items()
                            if name.endswith((".py", ".json"))}
        return C.guard_output_size(plan, cfg)

    written = []
    for name, text in files.items():
        path = os.path.join(target, name)
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        C.write_text_atomic(path, text)
        written.append({"file": name, "bytes": len(text.encode("utf-8")),
                        "sha256": _fingerprint(text)})
    history_path = os.path.join(target, "run_history.json")
    history = []
    if os.path.isfile(history_path):
        try:
            history = json.load(open(history_path, encoding="utf-8"))
            if not isinstance(history, list):
                history = []
        except (json.JSONDecodeError, OSError):
            history = []
    history.append({"generated_at": C.now_iso(), "goal": bundle["goal"],
                    "files": [w["file"] for w in written]})
    C.write_json_atomic(history_path, history[-MAX_BACKUPS:])
    return {
        "ok": True,
        "tool": PROG,
        "mode": "apply",
        "target": target,
        "archive": archive,
        "written": written,
        "file_count": len(written) + 1,
        "next_steps": [
            "python3 automation_entry.py --dry-run",
            "python3 tools_scaffold.py verify --project %s" % target,
            "python3 tools_scaffold.py export --project %s" % target,
        ],
    }


def _archive_existing(target):
    index = 1
    while True:
        candidate = "%s.bak-%d" % (target, index)
        if not os.path.exists(candidate):
            break
        index += 1
        if index > MAX_BACKUPS:
            raise C.FoundryError("too many backups (%d) for %s; clean them up first"
                                 % (MAX_BACKUPS, target), code="too_many_backups")
    shutil.move(target, candidate)
    return candidate


def cmd_verify(args, cfg):
    project = os.path.abspath(args.project)
    if not os.path.isdir(project):
        raise C.FoundryError("project directory not found: %s" % project,
                            code="missing_file")
    entry = os.path.join(project, "automation_entry.py")
    if not os.path.isfile(entry):
        raise C.FoundryError("no automation_entry.py in %s" % project,
                            code="bad_project")
    config_path = os.path.join(project, "config.json")
    config_doc = C.load_json(config_path, "project config")
    for key in ("input_dir", "output_dir"):
        value = config_doc.get(key)
        if not value:
            continue
        path = value if os.path.isabs(value) else os.path.join(project, value)
        os.makedirs(path, exist_ok=True)
    timeout = min(int(args.timeout or 120), 600)
    try:
        proc = subprocess.run(
            [sys.executable, entry, "--config", "config.json", "--dry-run"],
            cwd=project, capture_output=True, text=True, timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        raise C.FoundryError("generated project timed out after %s s" % timeout,
                            code="verify_timeout")
    result = {
        "ok": proc.returncode == 0,
        "tool": PROG,
        "project": project,
        "exit_code": proc.returncode,
        "dry_run": True,
        "stdout": proc.stdout[-4000:],
        "stderr": proc.stderr[-2000:],
        "checks": [
            {"check": "entry_point_runs", "ok": proc.returncode == 0},
            {"check": "dry_run_writes_nothing",
             "ok": "dry run" in proc.stdout.lower() or proc.returncode != 0},
        ],
    }
    if proc.returncode != 0:
        result["recovery"] = ("fix config.json paths or the validation errors shown in "
                              "stderr, then re-run verify")
    return result


def cmd_export(args, cfg):
    project = os.path.abspath(args.project)
    if not os.path.isdir(project):
        raise C.FoundryError("project directory not found: %s" % project, code="missing_file")
    name = args.name or os.path.basename(project.rstrip(os.sep))
    command = "%s %s" % (cfg.get("python_executable", "python3"),
                         os.path.join(project, "automation_entry.py"))
    launchers = project
    files = {}
    files["launch.sh"] = ("#!/usr/bin/env sh\nset -eu\ncd \"$(dirname \"$0\")\"\n"
                          "exec %s --config config.json \"$@\"\n" % command)
    files["launch.ps1"] = ("# PowerShell launcher for %s\n"
                           "Set-Location -LiteralPath $PSScriptRoot\n"
                           "& %s --config config.json @args\n"
                           "exit $LASTEXITCODE\n" % (name, command))
    files["systemd-user.service"] = (
        "[Unit]\nDescription=%s\n\n[Service]\nType=oneshot\nWorkingDirectory=%s\n"
        "ExecStart=%s --config config.json\n"
        "[Install]\nWantedBy=default.target\n" % (name, project, command))
    files["crontab.snippet"] = ("# %s - verify the host time zone first\n"
                                "30 2 * * * cd %s && %s --config config.json "
                                ">> logs/run.log 2>&1\n" % (name, project, command))
    written = []
    for filename, text in files.items():
        path = os.path.join(launchers, filename)
        C.write_text_atomic(path, text)
        written.append({"file": filename, "sha256": _fingerprint(text)})
    return {
        "ok": True,
        "tool": PROG,
        "project": project,
        "written": written,
        "note": "Launchers are written but never installed or registered.",
        "install_hint": "systemctl --user enable --now %s.service" % name,
    }


# --------------------------------------------------------------------------
# parser
# --------------------------------------------------------------------------

def build_parser():
    parser = argparse.ArgumentParser(
        prog=PROG,
        description="Generate, verify and export a runnable automation project.",
        epilog="Examples:\n"
               "  python3 tools_scaffold.py build --input bundle.json --out-dir workspace "
               "(dry-run)\n"
               "  python3 tools_scaffold.py build --input bundle.json --out-dir workspace --apply\n"
               "  python3 tools_scaffold.py verify --project workspace\n"
               "  python3 tools_scaffold.py export --project workspace",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--version", action="version",
                        version="%s %s" % (C.TOOL_NAME, C.TOOL_VERSION))
    C.add_common_arguments(parser)
    common = argparse.ArgumentParser(add_help=False)
    C.add_common_arguments(common, suppress=True)
    sub = parser.add_subparsers(dest="command", metavar="COMMAND")

    p = sub.add_parser("build", parents=[common], help="generate the project (dry-run by default)")
    p.add_argument("--input", required=True, metavar="BUNDLE", help="bundle JSON file")
    p.add_argument("--out-dir", metavar="DIR", help="target project directory")
    p.add_argument("--apply", action="store_true", help="actually write files")
    p.add_argument("--force", action="store_true",
                   help="archive an existing target directory and replace it")
    p.add_argument("--tool-name", metavar="NAME", help="entry point name metadata")
    p.add_argument("--retries", type=int, metavar="N", help="retry bound in the entry point")
    p.add_argument("--timeout", type=int, metavar="SECONDS", help="per-run timeout")
    p.add_argument("--audit-log", metavar="PATH", help="audit log path inside the project")
    p.add_argument("--input-dir", metavar="PATH", help="input directory in config")
    p.add_argument("--output-dir", metavar="PATH", help="output directory in config")
    p.set_defaults(func=cmd_build)

    p = sub.add_parser("verify", parents=[common], help="run a generated project in dry-run mode")
    p.add_argument("--project", required=True, metavar="DIR", help="generated project directory")
    p.add_argument("--timeout", type=int, metavar="SECONDS", help="verification timeout")
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("export", parents=[common], help="write launchers for the project")
    p.add_argument("--project", required=True, metavar="DIR", help="generated project directory")
    p.add_argument("--name", metavar="NAME", help="service/job name")
    p.set_defaults(func=cmd_export)
    return parser


def main(argv=None):
    return C.run_cli(PROG, build_parser, lambda a, c: a.func(a, c), argv)


if __name__ == "__main__":
    sys.exit(main())
