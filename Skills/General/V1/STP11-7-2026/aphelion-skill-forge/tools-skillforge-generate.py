#!/usr/bin/env python3
"""tools-skillforge-generate.py - render a runnable Skill Tool folder.

Loaded by tools-skillforge.py (primary entry point) and by the validators.
Renders, writes and then *executes* the generated skill tool so the emitted
folder is verified before it is reported as usable.

Standard library only. No template engine required: generated files are
rendered with explicit token replacement so braces in emitted code stay literal.
"""

from __future__ import annotations

