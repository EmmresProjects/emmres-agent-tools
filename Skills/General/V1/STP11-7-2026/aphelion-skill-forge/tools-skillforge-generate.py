LIB_NAME = "tools-skillforge-lib.py"


def _lib(here: Path):
    """Return the already-loaded forge lib module, or load it by path.

    Reusing the loaded instance matters: ForgeError is caught by the caller, so
    both files must share one class object rather than two copies of the module.
    """
    import importlib.util
    target = (here / LIB_NAME).resolve()
    if not target.exists():
        raise RuntimeError("Missing %s next to %s" % (LIB_NAME, Path(__file__).name))
    for module in list(sys.modules.values()):
        source = getattr(module, "__file__", None)
        if source and Path(source).resolve() == target and hasattr(module, "ForgeError"):
            return module
    name = "forge_lib_shared"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, target)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _fill(template: str, mapping: dict) -> str:
    out = template
    for key, value in mapping.items():
        out = out.replace("{{%s}}" % key, str(value))
    leftover = re.findall(r"\{\{[A-Z0-9_]+\}\}", out)
    if leftover:
        raise RuntimeError("Unfilled template tokens: %s" % sorted(set(leftover)))
    return out


def _py(value) -> str:
    """Python literal for embedding into generated source."""
    return repr(value)


def _json(value) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


