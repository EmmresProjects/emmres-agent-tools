CAPABILITY_BY_SLUG: Dict[str, Dict[str, Any]] = {item["slug"]: item for item in CAPABILITIES}
CAPABILITY_BY_NAME_LOWER: Dict[str, Dict[str, Any]] = {item["name"].lower(): item for item in CAPABILITIES}
CATEGORY_BY_ID: Dict[int, Dict[str, Any]] = {cat["category_id"]: cat for cat in CATEGORIES}
CATEGORY_BY_SLUG: Dict[str, Dict[str, Any]] = {cat["category_slug"]: cat for cat in CATEGORIES}


def resolve_capability(identifier: str) -> Optional[Dict[str, Any]]:
    """Resolve a capability by exact slug, case-insensitive name, or '<cat>.<skill>' / global number."""
    if not identifier:
        return None
    ident = identifier.strip()
    if ident in CAPABILITY_BY_SLUG:
        return CAPABILITY_BY_SLUG[ident]
    low = ident.lower()
    if low in CAPABILITY_BY_SLUG:
        return CAPABILITY_BY_SLUG[low]
    if low in CAPABILITY_BY_NAME_LOWER:
        return CAPABILITY_BY_NAME_LOWER[low]
    normalized = ""
    for ch in low:
        normalized += ch if ch.isalnum() else "-"
    while "--" in normalized:
        normalized = normalized.replace("--", "-")
    normalized = normalized.strip("-")
    if normalized in CAPABILITY_BY_SLUG:
        return CAPABILITY_BY_SLUG[normalized]
    if "." in ident:
        parts = ident.split(".", 1)
        if parts[0].isdigit() and parts[1].isdigit():
            cid, snum = int(parts[0]), int(parts[1])
            for item in CAPABILITIES:
                if item["category_id"] == cid and item["skill_number"] == snum:
                    return item
    if ident.isdigit():
        gidx = int(ident)
        for item in CAPABILITIES:
            if item["global_index"] == gidx:
                return item
    return None


def filter_capabilities(
    category: Optional[str] = None,
    search: Optional[str] = None,
    risk_class: Optional[str] = None,
    engine: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """Filter capabilities by category ID/slug/title, substring search, risk class, or engine."""
    results = CAPABILITIES
    if category:
        c_norm = category.strip().lower()
        if c_norm.isdigit():
            cid = int(c_norm)
            results = [c for c in results if c["category_id"] == cid]
        else:
            results = [
                c for c in results
                if c_norm == c["category_slug"] or c_norm in c["category_title"].lower()
            ]
    if risk_class:
        r_norm = risk_class.strip().lower()
        results = [c for c in results if c["risk_class"] == r_norm]
    if engine:
        e_norm = engine.strip().lower()
        results = [c for c in results if c["engine"] == e_norm]
    if search:
        q = search.strip().lower()
        results = [
            c for c in results
            if q in c["slug"] or q in c["name"].lower() or q in c["description"].lower() or q in c["category_title"].lower()
        ]
    return list(results)
